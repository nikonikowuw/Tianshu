func TestRequestIDAndHealthEndpoints(t *testing.T) {
	r := newTestEngine(t)
	httpserver.RegisterHealthRoutes(r, map[string]httpserver.ReadinessCheck{
		"postgres": func(context.Context) error { return nil },
	})

	req := httptest.NewRequest(http.MethodGet, "/healthz", nil)
	req.Header.Set("X-Request-Id", "req_valid_12345")
	rec := httptest.NewRecorder()
	r.ServeHTTP(rec, req)

	if rec.Code != http.StatusOK {
		t.Fatalf("/healthz status = %d, want 200", rec.Code)
	}
	if got := rec.Header().Get("X-Request-Id"); got != "req_valid_12345" {
		t.Fatalf("X-Request-Id = %q, want req_valid_12345", got)
	}

	// Invalid request ID must be regenerated by server.
	reqBad := httptest.NewRequest(http.MethodGet, "/readyz", nil)
	reqBad.Header.Set("X-Request-Id", "bad id!")
	recBad := httptest.NewRecorder()
	r.ServeHTTP(recBad, reqBad)
	if recBad.Code != http.StatusOK {
		t.Fatalf("/readyz status = %d, want 200", recBad.Code)
	}
	if got := recBad.Header().Get("X-Request-Id"); got == "" || got == "bad id!" {
		t.Fatalf("X-Request-Id = %q, expected server-generated ID", got)
	}
}

func TestAccessLogRedactsPathParameters(t *testing.T) {
	var logBuffer bytes.Buffer
	bundle := newTestBundle(t)
	engine, err := httpserver.NewEngine(httpserver.Options{
		Env:                "test",
		Logger:             logger.New("test", "info", &logBuffer),
		I18n:               bundle,
		RedactPathPrefixes: []string{"/api/v1/files/signed/"},
	})
	if err != nil {
		t.Fatalf("NewEngine() error = %v", err)
	}
	engine.GET("/api/v1/files/signed/:token", func(c *gin.Context) {
		c.Status(http.StatusOK)
	})

	const token = "sensitive-signed-token-value"
	req := httptest.NewRequest(http.MethodGet, "/api/v1/files/signed/"+token, nil)
	rec := httptest.NewRecorder()
	engine.ServeHTTP(rec, req)

	if rec.Code != http.StatusOK {
		t.Fatalf("status = %d, want 200", rec.Code)
	}
	logged := logBuffer.String()
	if strings.Contains(logged, token) {
		t.Fatalf("access log leaked signed URL token: %s", logged)
	}
	if !strings.Contains(logged, "/api/v1/files/signed/:token") {
		t.Fatalf("access log = %q, want matched route template", logged)
	}

	// NoRoute/405/uncleaned paths never get a matched template; fallback must clean & redact.
	for _, rawPath := range []string{
		"/api/v1/files/signed/" + token + "/extra",
		"//api/v1/files/signed/" + token,
		"/api/v1/files/signed/../signed/" + token,
	} {
		logBuffer.Reset()
		unmatched := httptest.NewRequest(http.MethodPost, rawPath, nil)
		unmatchedRec := httptest.NewRecorder()
		engine.ServeHTTP(unmatchedRec, unmatched)
		unmatchedLogged := logBuffer.String()
		if strings.Contains(unmatchedLogged, token) {
			t.Fatalf("unmatched access log (%s) leaked signed URL token: %s", rawPath, unmatchedLogged)
		}
		if !strings.Contains(unmatchedLogged, "/api/v1/files/signed/:token") {
			t.Fatalf("unmatched access log (%s) = %q, want redacted signed prefix", rawPath, unmatchedLogged)
		}
	}
}

